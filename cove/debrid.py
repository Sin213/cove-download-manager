"""Real-Debrid / AllDebrid link resolution.

Cove keeps the original hoster URL as the identity of a download. This
module turns that URL into a short-lived direct URL on the provider's
delivery node, which is handed straight to aria2 and then forgotten.

Two rules drive the whole design:

1. The generated node URL and the API credentials are secrets. They never
   appear in an exception, a log line, the database, or the UI. Every
   error raised here carries a fixed, human-readable sentence chosen by
   Cove — provider-supplied text is deliberately never echoed, because a
   provider is free to include the submitted link (and its query secrets)
   in its own message.
2. When no configured provider claims a host, resolution returns None and
   Cove downloads the URL directly, exactly as it always has.

Cached torrents (see the section at the foot of this module) reuse the same
rules with one twist: a torrent file's account-bound *locked* link is
stable, so it is persisted as the task's identity and unlocked into a node
URL on every launch, exactly as a hoster link would be.

Deliberately out of scope for this slice: folder and container links,
streaming-quality selection, AllDebrid redirectors, account-bound
share/landing links generated by someone else's account, and asking a
provider to fetch a torrent it does not already hold.

This module is intentionally Qt-free so it can be exercised without a
running event loop; the queue calls it from a background worker.
"""

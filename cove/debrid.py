def _rd_payload(resp, provider=REAL_DEBRID):
    """Provider error envelopes are checked before the HTTP status, because
    Real-Debrid returns its useful error codes alongside a 4xx."""
    body = _json_body(resp, provider)
    if isinstance(body, dict) and ("error_code" in body or "error" in body):
        code = body.get("error_code")
        if not isinstance(code, int) or isinstance(code, bool):
            code = None
        raise _error(provider, code, _RD_ERRORS)
    if not 200 <= getattr(resp, "status_code", 0) < 300:
        raise DebridError(provider, "http", _TRANSPORT, True, False)
    return body


def real_debrid_unrestrict(link: str, token: str, *, session=None) -> Unrestricted:
    resp = _request(
        session, "post", f"{RD_BASE}/unrestrict/link", REAL_DEBRID,
        headers=_bearer(token), data={"link": link},
    )
    body = _rd_payload(resp)
    if not isinstance(body, dict):
        raise _bad_response(REAL_DEBRID)
    return Unrestricted(
        download=_safe_download_url(body.get("download"), REAL_DEBRID),
        filename=_safe_filename(body.get("filename")),
        filesize=_safe_filesize(body.get("filesize"), REAL_DEBRID),
        provider=REAL_DEBRID,
    )


def real_debrid_account(token: str, *, session=None) -> dict:
    """Sanitized account summary for the Settings "Test" button."""
    resp = _request(session, "get", f"{RD_BASE}/user", REAL_DEBRID, headers=_bearer(token))
    body = _rd_payload(resp)
    if not isinstance(body, dict):
        raise _bad_response(REAL_DEBRID)
    account = {"username": body.get("username") if isinstance(body.get("username"), str) else ""}
    if isinstance(body.get("type"), str):
        account["type"] = body["type"]
    if isinstance(body.get("expiration"), str):
        account["expiration"] = body["expiration"]
    return account


def real_debrid_supported_domains(*, session=None) -> list[str]:
    resp = _request(session, "get", f"{RD_BASE}/hosts/domains", REAL_DEBRID)
    body = _rd_payload(resp)
    if not isinstance(body, list):
        raise _bad_response(REAL_DEBRID)
    return _normalize_domains(body)


# ---------------------------------------------------------------------------
# AllDebrid
# ---------------------------------------------------------------------------


def _ad_data(resp) -> dict:
    """Unwrap the AllDebrid {status, data|error} envelope."""
    body = _json_body(resp, ALL_DEBRID)
    if not isinstance(body, dict):
        raise _bad_response(ALL_DEBRID)
    if body.get("status") == "error":
        error = body.get("error")
        code = error.get("code") if isinstance(error, dict) else None
        if not isinstance(code, str):
            code = None
        raise _error(ALL_DEBRID, code, _AD_ERRORS)
    if body.get("status") != "success":
        raise _bad_response(ALL_DEBRID)
    data = body.get("data")
    if not isinstance(data, dict):
        raise _bad_response(ALL_DEBRID)
    return data


def _ad_call(session, method: str, path: str, apikey: str | None = None, data=None) -> dict:
    resp = _request(
        session, method, f"{AD_BASE}{path}", ALL_DEBRID,
        headers=_bearer(apikey) if apikey is not None else None,
        data=data,
    )
    return _ad_data(resp)


def all_debrid_unrestrict(
    link: str,
    apikey: str,
    *,
    session=None,
    sleep=time.sleep,
    clock=time.monotonic,
) -> Unrestricted:
    data = _ad_call(session, "post", "/link/unlock", apikey, {"link": link})
    filename = _safe_filename(data.get("filename"))
    filesize = _safe_filesize(data.get("filesize"), ALL_DEBRID)

    raw_link = data.get("link")
    if isinstance(raw_link, str) and raw_link:
        return Unrestricted(
            download=_safe_download_url(raw_link, ALL_DEBRID),
            filename=filename,
            filesize=filesize,
            provider=ALL_DEBRID,
        )

    delayed = data.get("delayed")
    if isinstance(delayed, bool) or not isinstance(delayed, (int, str)) or delayed in ("", 0):
        raise _bad_response(ALL_DEBRID)

    download = _await_delayed(delayed, apikey, session=session, sleep=sleep, clock=clock)
    # The delayed endpoint only returns the final link, so the name and size
    # from the unlock response are what the queue gets to work with.
    return Unrestricted(
        download=download,
        filename=filename,
        filesize=filesize,
        provider=ALL_DEBRID,
    )


def _await_delayed(delayed_id, apikey: str, *, session, sleep, clock) -> str:
    """Poll /link/delayed until the node link exists, or give up.

    Always sleeps before the first poll (the link is by definition not
    ready yet) and never polls faster than DELAYED_POLL_INTERVAL.
    """
    deadline = clock() + DELAYED_MAX_WAIT
    while True:
        sleep(DELAYED_POLL_INTERVAL)
        data = _ad_call(session, "post", "/link/delayed", apikey, {"id": delayed_id})
        status = data.get("status")
        if isinstance(status, bool) or not isinstance(status, int):
            raise _bad_response(ALL_DEBRID)
        if status == 2:
            return _safe_download_url(data.get("link"), ALL_DEBRID)
        if status == 3:
            raise DebridError(
                ALL_DEBRID, "delayed_failed",
                "could not generate a download link for this file.", False, False,
            )
        if status != 1:
            raise _bad_response(ALL_DEBRID)
        if clock() >= deadline:
            raise DebridError(
                ALL_DEBRID, "delayed_timeout",
                "took too long to prepare this download link. Try again shortly.",
                False, False,
            )


def all_debrid_account(apikey: str, *, session=None) -> dict:
    data = _ad_call(session, "get", "/user", apikey)
    user = data.get("user")
    if not isinstance(user, dict):
        raise _bad_response(ALL_DEBRID)
    account = {"username": user.get("username") if isinstance(user.get("username"), str) else ""}
    if isinstance(user.get("isPremium"), bool):
        account["is_premium"] = user["isPremium"]
    if isinstance(user.get("isTrial"), bool):
        account["is_trial"] = user["isTrial"]
    premium_until = user.get("premiumUntil")
    if isinstance(premium_until, int) and not isinstance(premium_until, bool):
        account["premium_until"] = premium_until
    return account


def all_debrid_supported_domains(*, session=None) -> list[str]:
    # The domains endpoint is public, so no key is sent. Only `hosts` is
    # used: streams and redirectors are out of scope for this slice.
    data = _ad_call(session, "get", "/hosts/domains")
    hosts = data.get("hosts")
    if not isinstance(hosts, list):
        raise _bad_response(ALL_DEBRID)
    return _normalize_domains(hosts)


# ---------------------------------------------------------------------------
# Host matching and the domain cache
# ---------------------------------------------------------------------------


def _normalize_domains(values) -> list[str]:
    out = []
    seen = set()
    for value in values:
        if not isinstance(value, str):
            continue
        domain = value.strip().lower().strip(".")
        if not domain or domain in seen:
            continue
        seen.add(domain)
        out.append(domain)
    return out


def _hostname(url) -> str:
    """Hostname of an http(s) URL, or "" for anything else.

    Parsing rather than string matching is the point here: it is what
    keeps `rapidgator.net.evil.com` and `?x=rapidgator.net` from matching.
    """
    if not isinstance(url, str) or not url:
        return ""
    try:
        parsed = urlparse(url)
    except ValueError:
        return ""
    if parsed.scheme.lower() not in ("http", "https"):
        return ""
    return (parsed.hostname or "").lower().strip(".")


def is_supported_domain(url, domains) -> bool:
    """Exact host match, or a subdomain on a dot boundary."""
    host = _hostname(url)
    if not host or not domains:
        return False
    for domain in domains:
        if not isinstance(domain, str):
            continue
        domain = domain.strip().lower().strip(".")
        if domain and (host == domain or host.endswith("." + domain)):
            return True
    return False


def is_provider_domain(url) -> bool:
    return is_supported_domain(url, PROVIDER_OWN_DOMAINS)


def _cache_path() -> Path:
    from .config import DATA_DIR

    return Path(DATA_DIR) / HOST_CACHE_FILE


def _read_cache() -> dict:
    try:
        raw = json.loads(_cache_path().read_text())
    except (OSError, ValueError):
        return {}
    return raw if isinstance(raw, dict) else {}


def _cached_entry(cache: dict, provider: str):
    """Return (domains, fetched_at) for a usable entry, else (None, 0.0)."""
    entry = cache.get(provider)
    if not isinstance(entry, dict):
        return None, 0.0
    domains = entry.get("domains")
    if not isinstance(domains, list):
        return None, 0.0
    fetched_at = entry.get("fetched_at")
    if isinstance(fetched_at, bool) or not isinstance(fetched_at, (int, float)):
        fetched_at = 0.0
    return _normalize_domains(domains), float(fetched_at)


def _write_cache(provider: str, domains: list[str]) -> None:
    cache = _read_cache()
    cache[provider] = {"fetched_at": time.time(), "domains": domains}
    path = _cache_path()
    try:
        path.parent.mkdir(parents=True, exist_ok=True)
        tmp = path.with_suffix(".json.tmp")
        tmp.write_text(json.dumps(cache))
        tmp.replace(path)
    except OSError:
        # A cache we cannot write is not worth failing a download over.
        pass


def supported_domains(provider: str, *, session=None, now=None) -> Optional[list[str]]:
    """Cached host list for a provider.

    Returns None when neither a cache nor a live fetch is available. The
    caller must read that as "unknown, treat the URL as a candidate" and
    let the resolve endpoint decide, rather than as "unsupported".
    """
    now = time.time() if now is None else now
    cached, fetched_at = _cached_entry(_read_cache(), provider)
    if cached is not None and 0 <= now - fetched_at < HOST_CACHE_TTL:
        return cached
    fetch = (
        all_debrid_supported_domains if provider == ALL_DEBRID
        else real_debrid_supported_domains
    )
    try:
        domains = fetch(session=session)
    except Exception:
        return cached  # stale list if we have one, else None
    _write_cache(provider, domains)
    return domains



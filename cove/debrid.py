@dataclass
class Unrestricted:
    """A resolved, ready-to-download link. `download` is a secret."""

    download: str
    filename: str
    filesize: int
    provider: str
    # TorBox only: the web-download (T1) or torrent (T2) item ID the queue
    # persists so a retry/restart can reuse it instead of creating another
    # one. Empty for AllDebrid/Real-Debrid, which have no such identity.
    item_id: str = ""


class DebridError(Exception):
    """A provider failure, already reduced to something safe to display.

    `user_message` is always one of Cove's own fixed strings. Nothing
    derived from the request (credential, submitted link) or the response
    (provider message, generated URL) is ever folded into it.
    """

    def __init__(
        self,
        provider: str,
        code,
        user_message: str,
        fallback_allowed: bool = False,
        host_unsupported: bool = False,
    ):
        self.provider = provider
        self.code = code
        self.user_message = user_message
        self.fallback_allowed = fallback_allowed
        self.host_unsupported = host_unsupported
        super().__init__(f"{provider_label(provider)}: {user_message}")


def provider_label(provider: str) -> str:
    return PROVIDER_LABELS.get(provider, "Debrid")



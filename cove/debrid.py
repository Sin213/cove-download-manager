"""Real-Debrid / AllDebrid link resolution.

Cove keeps the original hoster URL as the identity of a download. This
module turns that URL into a short-lived direct URL on the provider's
delivery node, which is handed straight to aria2 and then forgotten.

Two rules drive the whole design:

1. The generated node URL and the API credentials are secrets. They never
   appear in an exception, a log line, the database, or the UI. Every
   error raised here carries a fixed, human-readable sentence chosen by
   Cove — provider-supplied text is deliberately never echoed, because a
   provider is free to include the submitted link (and its query secrets)
   in its own message.
2. When no configured provider claims a host, resolution returns None and
   Cove downloads the URL directly, exactly as it always has.

Deliberately out of scope for this slice: torrents/magnets, folder and
container links, streaming-quality selection, AllDebrid redirectors, and
account-bound share/landing links generated by someone else's account.

This module is intentionally Qt-free so it can be exercised without a
running event loop; the queue calls it from a background worker.
"""
from __future__ import annotations

import json
import time
from dataclasses import dataclass
from pathlib import Path
from typing import Optional
from urllib.parse import urlparse

import requests

from .config import (
    DEBRID_ALL_DEBRID,
    DEBRID_DEFAULT_PROVIDER,
    DEBRID_PROVIDERS,
    DEBRID_REAL_DEBRID,
)

REAL_DEBRID = DEBRID_REAL_DEBRID
ALL_DEBRID = DEBRID_ALL_DEBRID
PROVIDERS = DEBRID_PROVIDERS
PROVIDER_LABELS = {REAL_DEBRID: "Real-Debrid", ALL_DEBRID: "AllDebrid"}

RD_BASE = "https://api.real-debrid.com/rest/1.0"
AD_BASE = "https://api.alldebrid.com/v4"

# (connect, read). Generous on read because unlock can be slow under load.
HTTP_TIMEOUT = (10, 30)

HOST_CACHE_FILE = "debrid_hosts.json"
HOST_CACHE_TTL = 24 * 60 * 60

# AllDebrid asks callers to poll a delayed link no faster than every five
# seconds. The deadline keeps a stuck generation from pinning a worker.
DELAYED_POLL_INTERVAL = 5.0
DELAYED_MAX_WAIT = 60.0

# Provider-owned domains. A URL on one of these is either already a
# generated node link or an account-bound landing page; re-resolving it
# would fail or silently produce someone else's download, so Cove leaves
# it on the normal direct path.
PROVIDER_OWN_DOMAINS = (
    "real-debrid.com",
    "alldebrid.com",
    "debrid.it",
)


@dataclass
class Unrestricted:
    """A resolved, ready-to-download link. `download` is a secret."""

    download: str
    filename: str
    filesize: int
    provider: str


class DebridError(Exception):
    """A provider failure, already reduced to something safe to display.

    `user_message` is always one of Cove's own fixed strings. Nothing
    derived from the request (credential, submitted link) or the response
    (provider message, generated URL) is ever folded into it.
    """

    def __init__(
        self,
        provider: str,
        code,
        user_message: str,
        fallback_allowed: bool = False,
        host_unsupported: bool = False,
    ):
        self.provider = provider
        self.code = code
        self.user_message = user_message
        self.fallback_allowed = fallback_allowed
        self.host_unsupported = host_unsupported
        super().__init__(f"{provider_label(provider)}: {user_message}")


def provider_label(provider: str) -> str:
    return PROVIDER_LABELS.get(provider, "Debrid")



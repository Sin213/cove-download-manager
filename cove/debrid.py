# ---------------------------------------------------------------------------
# TorBox
# ---------------------------------------------------------------------------
#
# TorBox's official SDKs (torbox-sdk-py, torbox-sdk-dotnet) expose no
# "cached-only" parameter on createwebdownload -- unlike AllDebrid/Real-Debrid
# unrestrict, there is no server-side guarantee against creating an uncached
# cloud job. Cove enforces cached-only behaviour itself: it calls the
# separate GET /webdl/checkcached endpoint first and only creates a web
# download when that reports the link cached. Any ambiguous or unparseable
# checkcached response is treated as "not cached", never as "cached" -- a
# false negative just skips TorBox for this link, while a false positive
# would create an uncached job Cove promised never to leave running.
#
# Exact error-code casing for TorBox's `error` field is not part of any
# published SDK/schema, so error classification here is done by HTTP status
# only (401/403 auth, 429 rate limit, 5xx temporary), matching the responses
# tables above in spirit without guessing string values TorBox may or may
# not actually return.


def _torbox_error_for_status(status: int) -> DebridError:
    if status in (401, 403):
        return DebridError(
            TORBOX, "auth",
            "the API token was rejected. Check the token in Settings.",
            False, False,
        )
    if status == 429:
        return DebridError(
            TORBOX, "rate_limited",
            "too many requests. Wait a moment and try again.", True, False,
        )
    if 500 <= status < 600:
        return DebridError(TORBOX, "http", _TRANSPORT, True, False)
    return _error(TORBOX, "unknown", {})


def _torbox_payload(resp):
    """Unwrap the {success, error, detail, data} envelope and return `data`.

    Provider `detail`/`error` text is deliberately never read here: only
    the HTTP status decides which fixed Cove message is raised.
    """
    body = _json_body(resp, TORBOX)
    status = getattr(resp, "status_code", 0)
    if not isinstance(body, dict) or body.get("success") is not True:
        if not 200 <= status < 300:
            raise _torbox_error_for_status(status)
        raise _bad_response(TORBOX)
    if not 200 <= status < 300:
        raise _torbox_error_for_status(status)
    return body.get("data")


def torbox_account(token: str, *, session=None) -> dict:
    """Sanitized account summary for the Settings "Test" button."""
    resp = _request(session, "get", f"{TORBOX_BASE}/user/me", TORBOX, headers=_bearer(token))
    data = _torbox_payload(resp)
    if not isinstance(data, dict):
        raise _bad_response(TORBOX)
    account: dict = {}
    email = data.get("email")
    if isinstance(email, str) and email:
        account["email"] = email
    if isinstance(data.get("is_subscribed"), bool):
        account["is_subscribed"] = data["is_subscribed"]
    expires = data.get("premium_expires_at")
    if isinstance(expires, str) and expires:
        account["expiration"] = expires
    return account


def torbox_supported_domains(*, session=None) -> list[str]:
    resp = _request(session, "get", f"{TORBOX_BASE}/webdl/hosters", TORBOX)
    data = _torbox_payload(resp)
    if not isinstance(data, list):
        raise _bad_response(TORBOX)
    domains: list[str] = []
    for entry in data:
        if not isinstance(entry, dict) or entry.get("status") is not True:
            continue
        entry_domains = entry.get("domains")
        if isinstance(entry_domains, list):
            domains.extend(entry_domains)
    return _normalize_domains(domains)


def _torbox_numeric_id(value, provider: str = TORBOX) -> str:
    """Round-trip an item/file ID through int() before it reaches a URL.

    Defence in depth: these values are either freshly returned by TorBox or
    read back from our own DB column, but neither source should ever be
    trusted enough to interpolate directly into a request. TorBox's own
    schema types these IDs as JSON numbers (e.g. `900.0`), which `int()`
    on the raw string form rejects outright, so a whole-valued float is
    normalized first; a fractional or non-finite one (`inf`/`nan`, whose
    `is_integer()` is also False) still falls through to the same
    rejection as any other malformed value.
    """
    if isinstance(value, bool):
        raise _bad_response(provider)
    if isinstance(value, float):
        if not value.is_integer():
            raise _bad_response(provider)
        value = int(value)
    try:
        return str(int(str(value)))
    except (TypeError, ValueError):
        raise _bad_response(provider) from None


def _torbox_check_cached(link: str, token: str, *, session=None) -> bool:
    import hashlib

    digest = hashlib.md5(link.encode("utf-8")).hexdigest()
    resp = _request(
        session, "get", f"{TORBOX_BASE}/webdl/checkcached?hash={digest}", TORBOX,
        headers=_bearer(token),
    )
    data = _torbox_payload(resp)
    if isinstance(data, dict):
        return bool(data.get(digest))
    if isinstance(data, list):
        return len(data) > 0
    return False


def _torbox_create_web_download(link: str, token: str, *, session=None) -> str:
    resp = _request(
        session, "post", f"{TORBOX_BASE}/webdl/createwebdownload", TORBOX,
        headers=_bearer(token), files={"link": (None, link)},
    )
    data = _torbox_payload(resp)
    if not isinstance(data, dict):
        raise _bad_response(TORBOX)
    item_id = data.get("webdownload_id")
    if isinstance(item_id, bool) or not isinstance(item_id, (str, int)) or not str(item_id):
        raise _bad_response(TORBOX)
    return _torbox_numeric_id(item_id)


def _torbox_mylist_entry(item_id: str, token: str, *, session=None):
    """The mylist row for one web download, or None when TorBox has no
    record of it (a missing item, not an error)."""
    safe_id = _torbox_numeric_id(item_id)
    resp = _request(
        session, "get", f"{TORBOX_BASE}/webdl/mylist?id={safe_id}", TORBOX,
        headers=_bearer(token),
    )
    data = _torbox_payload(resp)
    if data is None:
        return None
    if isinstance(data, list):
        data = data[0] if data else None
    if data is not None and not isinstance(data, dict):
        raise _bad_response(TORBOX)
    return data


def _torbox_delete_web_download(item_id: str, token: str, *, session=None) -> None:
    """Best-effort cleanup for a job Cove's own polling decided to abandon.

    Never allowed to raise: this only ever runs while another DebridError is
    about to be raised, and a cleanup failure must not replace or hide it.
    """
    try:
        safe_id = _torbox_numeric_id(item_id)
        _request(
            session, "post", f"{TORBOX_BASE}/webdl/controlwebdownload", TORBOX,
            headers=_bearer(token), data={"id": safe_id, "operation": "delete"},
        )
    except DebridError:
        pass


def _torbox_pick_file(files, provider: str = TORBOX):
    if not isinstance(files, list) or not files:
        raise _bad_response(provider)
    first = files[0]
    if not isinstance(first, dict):
        raise _bad_response(provider)
    file_id = first.get("id")
    if isinstance(file_id, bool) or not isinstance(file_id, (str, int)) or not str(file_id):
        raise _bad_response(provider)
    return (
        _torbox_numeric_id(file_id, provider),
        _safe_filename(first.get("name")),
        _safe_filesize(first.get("size"), provider),
    )


def _torbox_request_dl(kind: str, item_id: str, file_id: str, token: str, *, session=None) -> str:
    """Generate a temporary TorBox delivery URL without ever leaking the
    tokenized request URL that produces it.

    TorBox's requestdl takes the API token as a query parameter, so the
    request URL itself is a secret. `allow_redirects=False` and the
    explicit `redirect=false` query flag both keep this call from ever
    silently following a redirect to that secret URL. Transport exceptions
    are deliberately reduced to a fixed message with `from None`: a
    requests.RequestException can quote the request URL (including the
    token) in its own text, and that text must never reach a DebridError,
    a log line, or a test failure snapshot.
    """
    from urllib.parse import urlencode

    id_param = "web_id" if kind == "webdl" else "torrent_id"
    query = urlencode({
        "token": token,
        id_param: _torbox_numeric_id(item_id),
        "file_id": _torbox_numeric_id(file_id),
        "redirect": "false",
    })
    url = f"{TORBOX_BASE}/{kind}/requestdl?{query}"
    try:
        resp = _session(session).get(url, timeout=HTTP_TIMEOUT, allow_redirects=False)
    except Exception:
        raise DebridError(TORBOX, "transport", _TRANSPORT, True, False) from None
    data = _torbox_payload(resp)
    return _safe_torbox_delivery_url(data)


def _safe_torbox_delivery_url(value) -> str:
    url = _safe_download_url(value, TORBOX)
    if is_supported_domain(url, ("api.torbox.app",)):
        # TorBox's own API/requestdl host echoed back as "data" would still
        # carry the token in its query string; refuse it as a delivery URL
        # rather than hand it to aria2. A CDN delivery host is expected to
        # live elsewhere (e.g. a *.torbox.app storage/CDN subdomain other
        # than api.), so only the API host itself is excluded here.
        raise DebridError(
            TORBOX, "unsafe_url",
            "returned a link Cove will not download from.", False, False,
        )
    try:
        parsed = urlparse(url)
    except ValueError:
        raise _bad_response(TORBOX) from None
    if parsed.username or parsed.password:
        raise DebridError(
            TORBOX, "unsafe_url",
            "returned a link Cove will not download from.", False, False,
        )
    return url


def torbox_unrestrict(
    link: str,
    token: str,
    *,
    session=None,
    sleep=time.sleep,
    clock=time.monotonic,
) -> Unrestricted:
    """First-time TorBox hoster route: cached-only create, then unlock.

    Never leaves an uncached job running: a bounded ready-poll that times
    out deletes the item it created before raising.
    """
    if not isinstance(token, str) or not token.strip():
        raise DebridError(
            TORBOX, "missing_credential",
            "is enabled but has no API token saved. Add one in Settings.",
            False, False,
        )
    token = token.strip()
    if not _torbox_check_cached(link, token, session=session):
        raise DebridError(
            TORBOX, "not_cached",
            "this file is not already available in your TorBox account.",
            True, True,
        )
    item_id = _torbox_create_web_download(link, token, session=session)
    deadline = clock() + TORBOX_READY_MAX_WAIT
    while True:
        entry = _torbox_mylist_entry(item_id, token, session=session)
        if entry is None:
            raise _bad_response(TORBOX)
        if entry.get("download_present") is True or entry.get("download_finished") is True:
            break
        if clock() >= deadline:
            _torbox_delete_web_download(item_id, token, session=session)
            raise DebridError(
                TORBOX, "not_ready",
                "could not confirm this download was ready in time.", True, True,
            )
        sleep(TORBOX_READY_POLL_INTERVAL)
    file_id, filename, filesize = _torbox_pick_file(entry.get("files"))
    download = _torbox_request_dl("webdl", item_id, file_id, token, session=session)
    return Unrestricted(
        download=download, filename=filename, filesize=filesize,
        provider=TORBOX, item_id=item_id,
    )


def torbox_refresh_web_download(
    item_id: str,
    hoster_url: str,
    settings,
    *,
    session=None,
    sleep=time.sleep,
    clock=time.monotonic,
) -> Unrestricted:
    """Retry/restart route for a task already pinned to a TorBox item.

    A missing item soft-recreates once from the original hoster URL and the
    queue is expected to persist the replacement `item_id` it gets back. An
    item that exists but isn't ready, or any auth/malformed-response
    failure, is raised as-is: only "missing" recreates.
    """
    token = getattr(settings, "torbox_api_token", "")
    if not isinstance(token, str) or not token.strip():
        raise DebridError(
            TORBOX, "missing_credential",
            "is needed for this download but has no API token saved. "
            "Add one in Settings.",
            False, False,
        )
    token = token.strip()
    entry = _torbox_mylist_entry(item_id, token, session=session)
    if entry is None:
        return torbox_unrestrict(hoster_url, token, session=session, sleep=sleep, clock=clock)
    if not (entry.get("download_present") is True or entry.get("download_finished") is True):
        raise DebridError(
            TORBOX, "not_ready",
            "this TorBox item is not ready yet.", False, False,
        )
    file_id, filename, filesize = _torbox_pick_file(entry.get("files"))
    download = _torbox_request_dl("webdl", item_id, file_id, token, session=session)
    return Unrestricted(
        download=download, filename=filename, filesize=filesize,
        provider=TORBOX, item_id=item_id,
    )


def _torbox_file_id_present(files, file_id: str) -> bool:
    """Whether `file_id` still names one of the torrent's current files.

    A stale persisted `file_id` (the torrent was re-checked/re-selected on
    TorBox's side since materialisation) must not be sent to requestdl as
    if it were still valid.
    """
    if not isinstance(files, list):
        return False
    try:
        target = _torbox_numeric_id(file_id, TORBOX)
    except DebridError:
        return False
    for f in files:
        if not isinstance(f, dict):
            continue
        try:
            if _torbox_numeric_id(f.get("id"), TORBOX) == target:
                return True
        except DebridError:
            continue
    return False


def torbox_refresh_torrent_file(item_id: str, file_id: str, token: str, *, session=None) -> str:
    """Relaunch path for an already-materialised TorBox torrent-file row.

    Unlike the hoster route there is no original request to soft-recreate
    from if TorBox no longer has the item -- selecting files again would
    need the user's original file choice, which the queue does not keep.
    A missing item, an item that is not ready, or a file_id that no longer
    appears in the torrent's current file list are therefore all fixed
    errors, never a silent recreate.
    """
    if not isinstance(token, str) or not token.strip():
        raise DebridError(
            TORBOX, "missing_credential",
            "is needed for this download but has no API token saved. "
            "Add one in Settings.",
            False, False,
        )
    token = token.strip()
    entry = _torbox_torrent_entry(item_id, token, session=session)
    if entry is None:
        raise DebridError(
            TORBOX, "missing_item",
            "this TorBox torrent is no longer in your account. "
            "Re-add it to fetch it again.",
            False, False,
        )
    if not (entry.get("download_present") is True or entry.get("download_finished") is True):
        raise DebridError(
            TORBOX, "not_ready",
            "this TorBox torrent is not ready yet.", False, False,
        )
    if not _torbox_file_id_present(entry.get("files"), file_id):
        raise DebridError(
            TORBOX, "missing_item",
            "this file is no longer part of this TorBox torrent. "
            "Re-add it to fetch it again.",
            False, False,
        )
    return _torbox_request_dl("torrents", item_id, file_id, token, session=session)


def _torbox_check_cached_torrent(info_hash: str, token: str, *, session=None) -> bool:
    resp = _request(
        session, "get",
        f"{TORBOX_BASE}/torrents/checkcached?hash={info_hash}&format=list",
        TORBOX, headers=_bearer(token),
    )
    data = _torbox_payload(resp)
    if isinstance(data, dict):
        return bool(data.get(info_hash))
    if isinstance(data, list):
        return len(data) > 0
    return False


def _torbox_create_torrent(
    info_hash: str, token: str, *, torrent_bytes: bytes | None, session=None,
) -> Optional[str]:
    """Create a torrent under the account, refusing anything not cached.

    `add_only_if_cached` is TorBox's own server-side guarantee for this
    endpoint (unlike webdl's createwebdownload, which has none). `seed`
    and `allow_zip` are sent as ordinary multipart fields, matching the
    rest of this module's TorBox requests, so that a whole-torrent zip or
    post-completion seeding is never silently opted into by a provider
    default.

    Returns None when TorBox reports nothing was created -- the
    checkcached probe was a false positive, and nothing needs cleaning up.
    """
    parts = {
        "seed": (None, "3"),
        "allow_zip": (None, "false"),
        "add_only_if_cached": (None, "true"),
    }
    if torrent_bytes is not None:
        parts["file"] = ("cove.torrent", torrent_bytes, "application/x-bittorrent")
    else:
        parts["magnet"] = (None, _torrent.minimal_magnet(info_hash))
    resp = _request(
        session, "post", f"{TORBOX_BASE}/torrents/createtorrent", TORBOX,
        headers=_bearer(token), files=parts,
    )
    data = _torbox_payload(resp)
    if not isinstance(data, dict):
        raise _bad_response(TORBOX)
    torrent_id = data.get("torrent_id")
    if torrent_id is None or isinstance(torrent_id, bool):
        return None
    return _torbox_numeric_id(torrent_id)


def _torbox_torrent_entry(item_id: str, token: str, *, session=None):
    """The mylist row for one torrent, or None when TorBox has no record
    of it (a missing item, not an error)."""
    safe_id = _torbox_numeric_id(item_id)
    resp = _request(
        session, "get", f"{TORBOX_BASE}/torrents/mylist?id={safe_id}", TORBOX,
        headers=_bearer(token),
    )
    data = _torbox_payload(resp)
    if data is None:
        return None
    if isinstance(data, list):
        data = data[0] if data else None
    if data is not None and not isinstance(data, dict):
        raise _bad_response(TORBOX)
    return data


def _torbox_delete_torrent(item_id: str, token: str, *, session=None) -> None:
    """Best-effort cleanup for a job Cove's own probe decided to abandon.

    Never allowed to raise: this only ever runs while another outcome is
    about to be returned, and a cleanup failure must not replace it.
    controltorrent takes a JSON body, unlike the rest of this module's
    form-encoded TorBox requests.
    """
    try:
        safe_id = _torbox_numeric_id(item_id)
        _request(
            session, "post", f"{TORBOX_BASE}/torrents/controltorrent", TORBOX,
            headers={**_bearer(token), "Content-Type": "application/json"},
            data=json.dumps({"torrent_id": int(safe_id), "operation": "delete"}),
        )
    except DebridError:
        pass


def _torbox_cached_files(entry: dict, name: str, torrent_id: str) -> tuple:
    raw_files = entry.get("files")
    if not isinstance(raw_files, list) or not raw_files:
        raise _bad_response(TORBOX)
    if len(raw_files) > _MAX_CACHED_FILES:
        raise _bad_response(TORBOX)
    seen_ids: set = set()
    out = []
    for index, f in enumerate(raw_files):
        if not isinstance(f, dict):
            raise _bad_response(TORBOX)
        # _torbox_numeric_id rejects bools, non-integral/non-finite floats,
        # and anything int()-unconvertible (None, empty string, ...) --
        # TorBox's own schema types file IDs as JSON numbers.
        file_id = _torbox_numeric_id(f.get("id"), TORBOX)
        if file_id in seen_ids:
            raise _bad_response(TORBOX)
        seen_ids.add(file_id)
        raw_path = f.get("name")
        if not isinstance(raw_path, str) or not raw_path:
            raw_path = f.get("short_name")
        if not isinstance(raw_path, str) or not raw_path:
            raise _bad_response(TORBOX)
        parts = tuple(
            _torrent_component(p, TORBOX)
            for p in raw_path.replace("\\", "/").split("/") if p
        )
        if not parts:
            raise DebridError(
                TORBOX, "unsafe_path",
                "returned a file path Cove will not write to.", False, False,
            )
        out.append(CachedTorrentFile(
            index=index,
            path=_strip_root(name, parts),
            size=_safe_filesize(f.get("size"), TORBOX),
            item_id=torrent_id,
            file_id=file_id,
        ))
    return tuple(out)


def torbox_cached_torrent(
    info_hash: str,
    token: str,
    *,
    torrent_bytes: bytes | None = None,
    session=None,
    sleep=time.sleep,
    clock=time.monotonic,
) -> Optional[CachedTorrent]:
    """Return the torrent's files if TorBox already has it cached, else None.

    Cached-only is enforced twice: Cove's own checkcached probe first, and
    then TorBox's own `add_only_if_cached=true` on createtorrent, which
    refuses to create anything that is not already cached. A created item
    that still never reports ready is a cache race, not something to wait
    out -- it is deleted and reported as not cached rather than left to
    become an active TorBox download.
    """
    info_hash = _torrent.normalize_info_hash(info_hash)
    if torrent_bytes is not None and len(torrent_bytes) > _torrent.MAX_TORRENT_BYTES:
        raise _bad_response(TORBOX)
    if not _torbox_check_cached_torrent(info_hash, token, session=session):
        return None
    torrent_id = _torbox_create_torrent(
        info_hash, token, torrent_bytes=torrent_bytes, session=session,
    )
    if torrent_id is None:
        # add_only_if_cached refused the create: nothing exists to clean up.
        return None
    keep = False
    try:
        deadline = clock() + TORBOX_READY_MAX_WAIT
        while True:
            entry = _torbox_torrent_entry(torrent_id, token, session=session)
            if entry is None:
                raise _bad_response(TORBOX)
            if entry.get("download_present") is True or entry.get("download_finished") is True:
                break
            if clock() >= deadline:
                return None
            sleep(TORBOX_READY_POLL_INTERVAL)
        name = _torrent_root_name(entry.get("name"), info_hash, TORBOX)
        files = _torbox_cached_files(entry, name, torrent_id)
        keep = True
        return CachedTorrent(TORBOX, info_hash, name, files)
    finally:
        if not keep:
            _torbox_delete_torrent(torrent_id, token, session=session)



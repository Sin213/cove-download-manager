def _session(session):
    return requests if session is None else session


def _request(session, method: str, url: str, provider: str, *, headers=None, data=None, files=None):
    """Issue one bounded request. Transport failures become DebridError.

    Nothing about the request is logged; the caller only ever sees the
    fixed provider-named sentence.
    """
    call = getattr(_session(session), method)
    kwargs = {"headers": headers, "data": data, "timeout": HTTP_TIMEOUT}
    if files is not None:
        # Only multipart uploads pass this; keeping it out of the common
        # case means the existing call shape is untouched.
        kwargs["files"] = files
    try:
        return call(url, **kwargs)
    except Exception:
        raise DebridError(provider, "transport", _TRANSPORT, True, False) from None


def _json_body(resp, provider: str):
    try:
        return resp.json()
    except Exception:
        raise _bad_response(provider) from None


def _bearer(credential: str) -> dict:
    return {"Authorization": f"Bearer {credential}"}


def _safe_download_url(value, provider: str) -> str:
    """Accept only an http(s) URL. Rejection text never quotes the value."""
    if not isinstance(value, str) or not value:
        raise _bad_response(provider)
    try:
        scheme = urlparse(value).scheme.lower()
    except ValueError:
        raise _bad_response(provider) from None
    if scheme not in ("http", "https"):
        raise DebridError(
            provider, "unsafe_url",
            "returned a link Cove will not download from.", False, False,
        )
    return value


# Mirrors api_server.validate_filename, which is the canonical definition of
# a filename Cove considers safe. It is deliberately not imported here: that
# module pulls in the HTTP server, and cove.debrid is kept Qt-free and
# import-light. tests/test_debrid.py asserts the two rule sets agree.
_FILENAME_RESERVED_CHARS = '/\\:<>"|?*'
_WINDOWS_RESERVED_NAMES = frozenset(
    ("CON", "PRN", "AUX", "NUL")
    + tuple(f"COM{i}" for i in range(1, 10))
    + tuple(f"LPT{i}" for i in range(1, 10))
)


def _safe_filename(value) -> str:
    """Reduce a provider-supplied filename to something Cove will accept.

    Provider filenames are untrusted input and reach aria2 as the output
    name, so they must clear the same bar as a filename submitted through
    the local API. Anything that can't be made to clear it returns "",
    which simply means "no name" — aria2 then derives one itself and the
    download still runs. Rejecting the whole download over a bad name
    would be a worse outcome than letting aria2 name the file.
    """
    if not isinstance(value, str):
        return ""
    # Keep only the basename: the provider must never steer the write path.
    name = value.replace("\\", "/").rsplit("/", 1)[-1]
    name = "".join(c for c in name if ord(c) >= 32 and ord(c) != 127)
    # Windows rejects trailing spaces and periods outright.
    name = name.strip().rstrip(" .")
    if not name or len(name) > 255:
        return ""
    if any(char in name for char in _FILENAME_RESERVED_CHARS):
        return ""
    if name.split(".", 1)[0].upper() in _WINDOWS_RESERVED_NAMES:
        return ""
    return name


def _safe_filesize(value, provider: str) -> int:
    if value is None:
        return 0
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise _bad_response(provider)
    size = int(value)
    if size < 0:
        raise _bad_response(provider)
    return size



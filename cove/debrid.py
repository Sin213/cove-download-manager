def _error(provider: str, code, table: dict) -> DebridError:
    message, fallback, unsupported = table.get(code, _UNKNOWN)
    return DebridError(provider, code, message, fallback, unsupported)


def _bad_response(provider: str) -> DebridError:
    return DebridError(provider, "bad_response", _BAD_RESPONSE, False, False)



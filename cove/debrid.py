def _preferred(settings) -> str:
    preferred = getattr(settings, "debrid_preferred_provider", DEBRID_DEFAULT_PROVIDER)
    return preferred if preferred in PROVIDERS else DEBRID_DEFAULT_PROVIDER


def _enabled_providers(settings) -> list[tuple[str, str]]:
    """(provider, credential) pairs, preferred provider first.

    Remaining providers keep DEBRID_PROVIDERS' registration order (a stable
    sort on "is this the preferred one" preserves relative order for ties),
    so appending a provider there is what puts it last in the fallback
    chain. TorBox additionally requires the internal feature-availability
    gate: while it is off, TorBox never enters this list regardless of the
    user's torbox_enabled setting, so existing two-provider ordering is
    unaffected.
    """
    pairs = []
    if getattr(settings, "all_debrid_enabled", False) is True:
        pairs.append((ALL_DEBRID, getattr(settings, "all_debrid_api_key", "")))
    if getattr(settings, "real_debrid_enabled", False) is True:
        pairs.append((REAL_DEBRID, getattr(settings, "real_debrid_api_token", "")))
    if TORBOX_FEATURE_AVAILABLE and getattr(settings, "torbox_enabled", False) is True:
        pairs.append((TORBOX, getattr(settings, "torbox_api_token", "")))
    preferred = _preferred(settings)
    pairs.sort(key=lambda pair: 0 if pair[0] == preferred else 1)
    return pairs


def is_enabled(settings) -> bool:
    """True when the user has switched on at least one provider.

    The queue uses this to decide whether an http(s) task must go through
    the resolving worker. It deliberately ignores whether a credential is
    present: an enabled provider with an empty key has to reach resolve()
    so the user gets the "no API key saved" error, rather than silently
    getting a free-tier download from the hoster instead.
    """
    return bool(_enabled_providers(settings))


def _unrestrict(provider: str, url: str, credential: str, *, session, sleep, clock):
    if provider == ALL_DEBRID:
        return all_debrid_unrestrict(
            url, credential, session=session, sleep=sleep, clock=clock
        )
    if provider == TORBOX:
        return torbox_unrestrict(url, credential, session=session, sleep=sleep, clock=clock)
    return real_debrid_unrestrict(url, credential, session=session)


def resolve(
    url: str,
    settings,
    *,
    session=None,
    sleep=time.sleep,
    clock=time.monotonic,
) -> Optional[Unrestricted]:
    """Resolve `url` through the configured providers.

    Returns None when debrid does not apply — nothing enabled, not an
    http(s) URL, a provider-owned URL, or no enabled provider supports the
    host. In every one of those cases Cove downloads the URL directly.

    Raises DebridError when a provider that should have handled the link
    failed in a way the user needs to know about.
    """
    if not _hostname(url) or is_provider_domain(url):
        return None
    providers = _enabled_providers(settings)
    if not providers:
        return None

    errors: list[DebridError] = []
    for provider, credential in providers:
        domains = supported_domains(provider, session=session)
        if domains is not None and not is_supported_domain(url, domains):
            # This provider publishes a host list and this host isn't on
            # it; don't spend a request asking.
            continue
        if not isinstance(credential, str) or not credential.strip():
            raise DebridError(
                provider, "missing_credential",
                "is enabled but has no API key saved. Add one in Settings.",
                False, False,
            )
        try:
            return _unrestrict(
                provider, url, credential.strip(),
                session=session, sleep=sleep, clock=clock,
            )
        except DebridError as exc:
            if not exc.fallback_allowed:
                raise
            errors.append(exc)

    if errors and not all(exc.host_unsupported for exc in errors):
        # Something recoverable-looking went wrong everywhere. Surface the
        # last reason rather than quietly downloading the free-tier page.
        raise errors[-1]
    return None


# ---------------------------------------------------------------------------
# Cached torrents
# ---------------------------------------------------------------------------
#
# A torrent a provider already holds can be downloaded as ordinary HTTPS
# files, which is the whole point of this route. Cove only ever *probes*:
# it never asks a provider to fetch a torrent it does not already have, and
# it deletes any entry its probe created. That keeps the user's provider
# account from filling up with torrents Cove decided not to use.
#
# Two things are deliberately never sent to a provider: the user's original
# magnet (it can carry a private-tracker passkey in `tr=`) and anything
# derived from it beyond the info hash.

# Real-Debrid resolves a magnet to metadata asynchronously. That conversion
# is the only wait Cove will sit through -- it is not the torrent being
# downloaded, it is the provider looking the torrent up.
RD_TORRENT_POLL_INTERVAL = 2.0
RD_TORRENT_MAX_WAIT = 15.0

# Real-Debrid states that mean the provider is (or would be) fetching the
# torrent itself. Seeing any of these means "not cached", full stop.
_RD_ACTIVE_STATES = frozenset({"queued", "downloading", "compressing", "uploading"})
_RD_DEAD_STATES = frozenset({"error", "virus", "dead", "magnet_error"})

_MAX_CACHED_FILES = 20_000
_MAX_TREE_DEPTH = 32


@dataclass
class CachedTorrentFile:
    """One file of a cached torrent.

    `locked_link` is AllDebrid/Real-Debrid's account-bound link. It is not
    a download URL: it has to be unlocked into a short-lived node URL
    first, exactly like a hoster link. Unlike the node URL it is stable,
    so it is what gets persisted.

    TorBox has no such per-file link: `item_id`/`file_id` identify the
    torrent and file instead, and requestdl regenerates a delivery URL
    from them on every launch. Exactly one of `locked_link` or the
    `item_id`/`file_id` pair is populated, depending on provider.
    """

    index: int
    path: tuple[str, ...]
    size: int
    locked_link: str = ""
    item_id: str = ""
    file_id: str = ""

    @property
    def relative_path(self) -> str:
        return "/".join(self.path)


@dataclass
class CachedTorrent:
    provider: str
    info_hash: str
    name: str
    files: tuple[CachedTorrentFile, ...]

    @property
    def multi_file(self) -> bool:
        return len(self.files) > 1 or any(len(f.path) > 1 for f in self.files)

    def destination_parts(self, file: CachedTorrentFile) -> tuple[str, ...]:
        """Path components for `file` below the chosen output directory."""
        return (self.name,) + file.path if self.multi_file else file.path


def _torrent_component(value, provider: str) -> str:
    """Validate one provider-supplied path component.

    The provider's file tree is untrusted for exactly the same reason the
    torrent's own is: it names files Cove is about to create.
    """
    try:
        return _torrent.safe_component(value)
    except _torrent.TorrentError:
        raise DebridError(
            provider, "unsafe_path",
            "returned a file path Cove will not write to.", False, False,
        ) from None


def _torrent_root_name(value, info_hash: str, provider: str) -> str:
    """Safe folder name for the torrent, falling back to its info hash.

    The hash is not a secret -- it is the public identity of the torrent
    and is already stored in the local database -- so it is a usable last
    resort when the provider's name can't be made safe.
    """
    try:
        return _torrent.safe_component(value)
    except _torrent.TorrentError:
        return info_hash


def _strip_root(name: str, parts: tuple[str, ...]) -> tuple[str, ...]:
    """Drop a leading folder that just repeats the torrent name.

    AllDebrid's tree roots a multi-file torrent under its own name; the
    queue adds that folder itself, so keeping it would nest twice.
    """
    if len(parts) > 1 and parts[0] == name:
        return parts[1:]
    return parts


# --- AllDebrid -------------------------------------------------------------


def _ad_delete_magnet(session, apikey: str, magnet_id) -> None:
    """Best-effort removal of a probe entry, with one retry.

    Never raises: a failure here must not mask the real outcome, and the
    caller has nothing useful to do about it. Nothing is logged, because
    the only things worth logging are the key and the entry id.
    """
    for attempt in (0, 1):
        try:
            _ad_call(session, "post", "/magnet/delete", apikey, {"id": magnet_id})
            return
        except DebridError as exc:
            # Retry once for a transport blip; a refusal will not get better.
            if attempt == 1 or exc.code != "transport":
                return


def _ad_entry(data: dict, key: str) -> dict:
    entries = data.get(key)
    if not isinstance(entries, list) or len(entries) != 1:
        raise _bad_response(ALL_DEBRID)
    entry = entries[0]
    if not isinstance(entry, dict):
        raise _bad_response(ALL_DEBRID)
    if entry.get("error"):
        error = entry["error"]
        code = error.get("code") if isinstance(error, dict) else None
        raise _error(ALL_DEBRID, code if isinstance(code, str) else None, _AD_ERRORS)
    return entry


def _ad_flatten(nodes, prefix: tuple[str, ...], out: list, depth: int) -> None:
    if depth > _MAX_TREE_DEPTH or not isinstance(nodes, list):
        raise _bad_response(ALL_DEBRID)
    for node in nodes:
        if not isinstance(node, dict):
            raise _bad_response(ALL_DEBRID)
        part = _torrent_component(node.get("n"), ALL_DEBRID)
        entries = node.get("e")
        if isinstance(entries, list):
            _ad_flatten(entries, prefix + (part,), out, depth + 1)
            continue
        link = node.get("l")
        if not isinstance(link, str) or not link:
            raise DebridError(
                ALL_DEBRID, "missing_link",
                "did not return a download link for one of this torrent's files.",
                False, False,
            )
        if len(out) >= _MAX_CACHED_FILES:
            raise _bad_response(ALL_DEBRID)
        out.append((
            prefix + (part,),
            _safe_filesize(node.get("s"), ALL_DEBRID),
            _safe_download_url(link, ALL_DEBRID),
        ))


def _ad_cached_files(session, apikey: str, magnet_id, name: str) -> tuple:
    data = _ad_call(session, "post", "/magnet/files", apikey, {"id[]": magnet_id})
    entry = _ad_entry(data, "magnets")
    flat: list = []
    _ad_flatten(entry.get("files"), (), flat, 0)
    if not flat:
        raise _bad_response(ALL_DEBRID)
    return tuple(
        CachedTorrentFile(
            index=index,
            path=_strip_root(name, parts),
            size=size,
            locked_link=link,
        )
        for index, (parts, size, link) in enumerate(flat)
    )


def all_debrid_cached_torrent(
    info_hash: str,
    apikey: str,
    *,
    torrent_bytes: bytes | None = None,
    session=None,
) -> Optional[CachedTorrent]:
    """Return the torrent's files if AllDebrid already has it, else None.

    An entry created by this probe is deleted unless it turns out to hold
    the cached files we are about to download from.
    """
    info_hash = _torrent.normalize_info_hash(info_hash)
    if torrent_bytes is not None:
        if len(torrent_bytes) > _torrent.MAX_TORRENT_BYTES:
            raise _bad_response(ALL_DEBRID)
        resp = _request(
            session, "post", f"{AD_BASE}/magnet/upload/file", ALL_DEBRID,
            headers=_bearer(apikey),
            files={"files[0]": ("cove.torrent", torrent_bytes, "application/x-bittorrent")},
        )
        entry = _ad_entry(_ad_data(resp), "files")
    else:
        data = _ad_call(
            session, "post", "/magnet/upload", apikey,
            {"magnets[]": _torrent.minimal_magnet(info_hash)},
        )
        entry = _ad_entry(data, "magnets")

    magnet_id = entry.get("id")
    if magnet_id is None:
        raise _bad_response(ALL_DEBRID)
    keep = False
    try:
        if entry.get("ready") is not True:
            # Not cached. Cove does not wait for AllDebrid to fetch it.
            return None
        name = _torrent_root_name(entry.get("name") or entry.get("filename"), info_hash, ALL_DEBRID)
        files = _ad_cached_files(session, apikey, magnet_id, name)
        keep = True
        return CachedTorrent(ALL_DEBRID, info_hash, name, files)
    finally:
        if not keep:
            _ad_delete_magnet(session, apikey, magnet_id)


# --- Real-Debrid -----------------------------------------------------------


def _rd_no_content(resp) -> None:
    """Accept a 2xx with no body; map an error envelope if there is one."""
    if 200 <= getattr(resp, "status_code", 0) < 300:
        return
    try:
        body = resp.json()
    except Exception:
        body = None
    if isinstance(body, dict) and ("error_code" in body or "error" in body):
        code = body.get("error_code")
        if not isinstance(code, int) or isinstance(code, bool):
            code = None
        raise _error(REAL_DEBRID, code, _RD_ERRORS)
    raise DebridError(REAL_DEBRID, "http", _TRANSPORT, True, False)


def _rd_delete_torrent(session, token: str, torrent_id) -> None:
    """Best-effort removal of a probe entry, with one retry. Never raises."""
    for attempt in (0, 1):
        try:
            resp = _request(
                session, "delete", f"{RD_BASE}/torrents/delete/{torrent_id}",
                REAL_DEBRID, headers=_bearer(token),
            )
            _rd_no_content(resp)
            return
        except DebridError as exc:
            if attempt == 1 or exc.code not in ("transport", "http"):
                return


def _rd_cached_files(info: dict, info_hash: str) -> tuple:
    name = _torrent_root_name(info.get("filename"), info_hash, REAL_DEBRID)
    raw_files = info.get("files")
    links = info.get("links")
    if not isinstance(raw_files, list) or not isinstance(links, list):
        raise _bad_response(REAL_DEBRID)
    selected = [f for f in raw_files if isinstance(f, dict) and f.get("selected")]
    if not selected or len(selected) != len(links):
        # links are positional against the selected files; a mismatch means
        # we cannot say which link belongs to which path.
        raise _bad_response(REAL_DEBRID)
    if len(selected) > _MAX_CACHED_FILES:
        raise _bad_response(REAL_DEBRID)
    out = []
    for index, (entry, link) in enumerate(zip(selected, links)):
        raw_path = entry.get("path")
        if not isinstance(raw_path, str) or not raw_path:
            raise _bad_response(REAL_DEBRID)
        parts = tuple(
            _torrent_component(p, REAL_DEBRID)
            for p in raw_path.split("/") if p
        )
        if not parts:
            raise DebridError(
                REAL_DEBRID, "unsafe_path",
                "returned a file path Cove will not write to.", False, False,
            )
        out.append(CachedTorrentFile(
            index=index,
            path=_strip_root(name, parts),
            size=_safe_filesize(entry.get("bytes"), REAL_DEBRID),
            locked_link=_safe_download_url(link, REAL_DEBRID),
        ))
    return name, tuple(out)


def real_debrid_cached_torrent(
    info_hash: str,
    token: str,
    *,
    torrent_bytes: bytes | None = None,
    session=None,
    sleep=time.sleep,
    clock=time.monotonic,
) -> Optional[CachedTorrent]:
    """Return the torrent's files if Real-Debrid already has it, else None.

    Real-Debrid has no cache-lookup endpoint, so the probe adds the torrent
    and reads its state. The only state Cove waits on is
    `magnet_conversion` (the provider resolving metadata). The moment an
    actual fetch state appears the answer is "not cached" -- waiting for a
    download to finish would be Cove sitting on a torrent for an hour and
    then calling it cached.
    """
    info_hash = _torrent.normalize_info_hash(info_hash)
    if torrent_bytes is not None:
        if len(torrent_bytes) > _torrent.MAX_TORRENT_BYTES:
            raise _bad_response(REAL_DEBRID)
        resp = _request(
            session, "put", f"{RD_BASE}/torrents/addTorrent", REAL_DEBRID,
            headers=_bearer(token), data=torrent_bytes,
        )
    else:
        resp = _request(
            session, "post", f"{RD_BASE}/torrents/addMagnet", REAL_DEBRID,
            headers=_bearer(token),
            data={"magnet": _torrent.minimal_magnet(info_hash)},
        )
    body = _rd_payload(resp)
    torrent_id = body.get("id") if isinstance(body, dict) else None
    if not torrent_id:
        raise _bad_response(REAL_DEBRID)

    keep = False
    try:
        deadline = clock() + RD_TORRENT_MAX_WAIT
        selected = False
        while True:
            info = _rd_payload(_request(
                session, "get", f"{RD_BASE}/torrents/info/{torrent_id}",
                REAL_DEBRID, headers=_bearer(token),
            ))
            if not isinstance(info, dict):
                raise _bad_response(REAL_DEBRID)
            status = info.get("status")
            if not isinstance(status, str):
                raise _bad_response(REAL_DEBRID)

            if status in _RD_ACTIVE_STATES or status in _RD_DEAD_STATES:
                # Provider would have to fetch it (or can't): not cached.
                return None
            if status == "downloaded":
                name, files = _rd_cached_files(info, info_hash)
                keep = True
                return CachedTorrent(REAL_DEBRID, info_hash, name, files)
            if status == "waiting_files_selection":
                if selected:
                    # Selecting twice would be a loop, not progress.
                    return None
                selected = True
                _rd_no_content(_request(
                    session, "post", f"{RD_BASE}/torrents/selectFiles/{torrent_id}",
                    REAL_DEBRID, headers=_bearer(token), data={"files": "all"},
                ))
                continue
            if status != "magnet_conversion":
                raise _bad_response(REAL_DEBRID)
            if clock() >= deadline:
                # Still converting. Treat as not cached rather than wait.
                return None
            sleep(RD_TORRENT_POLL_INTERVAL)
    finally:
        if not keep:
            _rd_delete_torrent(session, token, torrent_id)


# --- Shared torrent routing ------------------------------------------------


def _probe_cached(provider: str, info_hash: str, credential: str, *, torrent_bytes, session, sleep, clock):
    if provider == ALL_DEBRID:
        return all_debrid_cached_torrent(
            info_hash, credential, torrent_bytes=torrent_bytes, session=session
        )
    if provider == TORBOX:
        return torbox_cached_torrent(
            info_hash, credential, torrent_bytes=torrent_bytes,
            session=session, sleep=sleep, clock=clock,
        )
    return real_debrid_cached_torrent(
        info_hash, credential, torrent_bytes=torrent_bytes,
        session=session, sleep=sleep, clock=clock,
    )


def resolve_torrent(
    info_hash: str,
    settings,
    *,
    torrent_bytes: bytes | None = None,
    session=None,
    sleep=time.sleep,
    clock=time.monotonic,
) -> Optional[CachedTorrent]:
    """Ask each enabled provider, preferred first, whether it has this torrent.

    Returns the first cached hit, or None when no enabled provider has it.
    "Not cached" is an ordinary answer and moves on to the next provider; a
    credential or account failure is not, and is raised so the user finds
    out their key is wrong instead of silently getting no torrent support.
    """
    providers = _enabled_providers(settings)
    if not providers:
        return None

    errors: list[DebridError] = []
    for provider, credential in providers:
        if not isinstance(credential, str) or not credential.strip():
            raise DebridError(
                provider, "missing_credential",
                "is enabled but has no API key saved. Add one in Settings.",
                False, False,
            )
        try:
            found = _probe_cached(
                provider, info_hash, credential.strip(),
                torrent_bytes=torrent_bytes, session=session,
                sleep=sleep, clock=clock,
            )
        except DebridError as exc:
            if not exc.fallback_allowed:
                raise
            errors.append(exc)
            continue
        if found is not None:
            return found
    if errors:
        raise errors[-1]
    return None


def unlock_torrent_file(locked_link: str, provider: str, settings, *, session=None,
                        sleep=time.sleep, clock=time.monotonic) -> Unrestricted:
    """Turn a stored account-bound torrent link into a fresh node URL.

    This is the relaunch path for a materialised torrent file row. It is
    pinned to the provider that produced the link -- the other provider
    cannot unlock it -- so there is no fallback here. TorBox never reaches
    this function: it has no locked link to unlock, and is relaunched
    through `torbox_refresh_torrent_file` instead. `PROVIDERS` is not used
    for this check because it also lists TorBox, which -- unlike
    AllDebrid/Real-Debrid -- has no per-file credential lookup below.
    """
    if provider not in (ALL_DEBRID, REAL_DEBRID):
        raise DebridError(
            provider, "unknown_provider",
            "is no longer available for this download.", False, False,
        )
    credential = (
        getattr(settings, "all_debrid_api_key", "") if provider == ALL_DEBRID
        else getattr(settings, "real_debrid_api_token", "")
    )
    if not isinstance(credential, str) or not credential.strip():
        raise DebridError(
            provider, "missing_credential",
            "is needed for this torrent download but has no API key saved. "
            "Add one in Settings.",
            False, False,
        )
    return _unrestrict(
        provider, locked_link, credential.strip(),
        session=session, sleep=sleep, clock=clock,
    )

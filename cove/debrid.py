def _preferred(settings) -> str:
    preferred = getattr(settings, "debrid_preferred_provider", DEBRID_DEFAULT_PROVIDER)
    return preferred if preferred in PROVIDERS else DEBRID_DEFAULT_PROVIDER


def _enabled_providers(settings) -> list[tuple[str, str]]:
    """(provider, credential) pairs, preferred provider first."""
    pairs = []
    if getattr(settings, "all_debrid_enabled", False) is True:
        pairs.append((ALL_DEBRID, getattr(settings, "all_debrid_api_key", "")))
    if getattr(settings, "real_debrid_enabled", False) is True:
        pairs.append((REAL_DEBRID, getattr(settings, "real_debrid_api_token", "")))
    preferred = _preferred(settings)
    pairs.sort(key=lambda pair: 0 if pair[0] == preferred else 1)
    return pairs


def is_enabled(settings) -> bool:
    """True when the user has switched on at least one provider.

    The queue uses this to decide whether an http(s) task must go through
    the resolving worker. It deliberately ignores whether a credential is
    present: an enabled provider with an empty key has to reach resolve()
    so the user gets the "no API key saved" error, rather than silently
    getting a free-tier download from the hoster instead.
    """
    return bool(_enabled_providers(settings))


def _unrestrict(provider: str, url: str, credential: str, *, session, sleep, clock):
    if provider == ALL_DEBRID:
        return all_debrid_unrestrict(
            url, credential, session=session, sleep=sleep, clock=clock
        )
    return real_debrid_unrestrict(url, credential, session=session)


def resolve(
    url: str,
    settings,
    *,
    session=None,
    sleep=time.sleep,
    clock=time.monotonic,
) -> Optional[Unrestricted]:
    """Resolve `url` through the configured providers.

    Returns None when debrid does not apply — nothing enabled, not an
    http(s) URL, a provider-owned URL, or no enabled provider supports the
    host. In every one of those cases Cove downloads the URL directly.

    Raises DebridError when a provider that should have handled the link
    failed in a way the user needs to know about.
    """
    if not _hostname(url) or is_provider_domain(url):
        return None
    providers = _enabled_providers(settings)
    if not providers:
        return None

    errors: list[DebridError] = []
    for provider, credential in providers:
        domains = supported_domains(provider, session=session)
        if domains is not None and not is_supported_domain(url, domains):
            # This provider publishes a host list and this host isn't on
            # it; don't spend a request asking.
            continue
        if not isinstance(credential, str) or not credential.strip():
            raise DebridError(
                provider, "missing_credential",
                "is enabled but has no API key saved. Add one in Settings.",
                False, False,
            )
        try:
            return _unrestrict(
                provider, url, credential.strip(),
                session=session, sleep=sleep, clock=clock,
            )
        except DebridError as exc:
            if not exc.fallback_allowed:
                raise
            errors.append(exc)

    if errors and not all(exc.host_unsupported for exc in errors):
        # Something recoverable-looking went wrong everywhere. Surface the
        # last reason rather than quietly downloading the free-tier page.
        raise errors[-1]
    return None
